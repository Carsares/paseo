export function useGitP2Copy() {
  const { i18n } = useTranslation();
  const locale = resolveSupportedLocale("system", [
    i18n?.resolvedLanguage ?? i18n?.language ?? "en",
  ]);
  const [
    selectLines,
    selectRange,
    stageLines,
    unstageLines,
    blame,
    uncommitted,
    blameUnavailable,
    blameTruncated,
    openMerge,
    mergeUnavailable,
    base,
    result,
    editResult,
    previewResult,
    saveResult,
    localTags,
    createTag,
    deleteTag,
    pushTag,
    tagName,
    remote,
    noTags,
    noRemotes,
    forcePush,
    forceDelete,
    typeConfirmation,
    staleRemote,
    missingVersion,
    ours,
    theirs,
    noBranches,
    noUpstream,
  ] = copies[locale];
  return {
    selectLines,
    selectRange,
    stageLines,
    unstageLines,
    blame,
    uncommitted,
    blameUnavailable,
    blameTruncated,
    openMerge,
    mergeUnavailable,
    base,
    result,
    editResult,
    previewResult,
    saveResult,
    localTags,
    createTag,
    deleteTag,
    pushTag,
    tagName,
    remote,
    noTags,
    noRemotes,
    forcePush,
    forceDelete,
    typeConfirmation,
    staleRemote,
    missingVersion,
    ours,
    theirs,
    noBranches,
    noUpstream,
  };
}
